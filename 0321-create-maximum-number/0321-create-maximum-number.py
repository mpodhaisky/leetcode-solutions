class Solution:
    def bignum(self,nums,digits):
        mono=[]
        for i , n in enumerate(nums):
            while mono and mono[-1]<n and len(nums)-i > digits-len(mono): mono.pop()
            mono.append(n)

        return mono[:digits]
            
    def maxNumber(self, nums1: List[int], nums2: List[int], K: int) -> List[int]:
        ret=[]
        if nums1 > nums2: nums1, nums2 = nums2, nums1
        for i in range(max(0,K -len(nums2)),min(K,len(nums1))+1):
            cur=[]
            A=self.bignum(nums1,i)
            B=self.bignum(nums2,K-i)
            j=k=0
            while j <len(A) and k<len(B):
                if A[j:]>B[k:]:
                    cur.append(A[j])
                    j+=1
                else:
                    cur.append(B[k])
                    k+=1
            cur+=A[j:] + B[k:]
            ret=max(ret,cur)
        return ret
